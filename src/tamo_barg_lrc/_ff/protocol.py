"""Minimal typed protocols and shared exceptions for the finite-field backend."""

from __future__ import annotations

from collections.abc import Iterator, Sequence
from typing import Any, Protocol, runtime_checkable


class DecodingError(Exception):
    """Raised when bounded-distance decoding fails or erasure count >= d."""


@runtime_checkable
class FieldElementProtocol(Protocol):
    """Immutable, hashable scalar in ``GF(p^m)``."""

    def is_zero(self) -> bool: ...
    def to_integer(self) -> int: ...
    def parent(self) -> Any: ...
    def __add__(self, other: Any) -> Any: ...
    def __sub__(self, other: Any) -> Any: ...
    def __neg__(self) -> Any: ...
    def __mul__(self, other: Any) -> Any: ...
    def __truediv__(self, other: Any) -> Any: ...
    def __pow__(self, exp: int) -> Any: ...
    def __eq__(self, other: object) -> bool: ...
    def __hash__(self) -> int: ...


@runtime_checkable
class FiniteFieldProtocol(Protocol):
    """Finite field ``GF(q)`` with ``q = p^m``."""

    def order(self) -> int: ...
    def cardinality(self) -> int: ...
    def characteristic(self) -> int: ...
    def degree(self) -> int: ...
    def is_finite(self) -> bool: ...
    def is_field(self) -> bool: ...
    def zero(self) -> Any: ...
    def one(self) -> Any: ...
    def gen(self) -> Any: ...
    def primitive_element(self) -> Any: ...
    def multiplicative_generator(self) -> Any: ...
    def from_integer(self, i: int) -> Any: ...
    def fetch_int(self, i: int) -> Any: ...
    def __call__(self, x: Any) -> Any: ...
    def __iter__(self) -> Iterator[Any]: ...
    def __len__(self) -> int: ...


@runtime_checkable
class FFVectorProtocol(Protocol):
    """1D vector over ``GF(q)`` supporting optional immutability."""

    def __len__(self) -> int: ...
    def __getitem__(self, idx: int | slice) -> Any: ...
    def __setitem__(self, idx: int, val: Any) -> None: ...
    def __iter__(self) -> Iterator[Any]: ...
    def __add__(self, other: Any) -> Any: ...
    def __sub__(self, other: Any) -> Any: ...
    def __neg__(self) -> Any: ...
    def __eq__(self, other: object) -> bool: ...
    def copy(self) -> Any: ...
    def set_immutable(self) -> None: ...
    def is_immutable(self) -> bool: ...
    def is_zero(self) -> bool: ...
    def hamming_weight(self) -> int: ...
    def list(self) -> list[Any]: ...
    def parent(self) -> Any: ...


@runtime_checkable
class FFMatrixProtocol(Protocol):
    """Dense 2D matrix over ``GF(q)`` (supports 0-row matrices)."""

    def nrows(self) -> int: ...
    def ncols(self) -> int: ...
    def rows(self) -> list[Any]: ...
    def row(self, i: int) -> Any: ...
    def columns(self) -> list[Any]: ...
    def column(self, j: int) -> Any: ...
    def transpose(self) -> Any: ...
    def rank(self) -> int: ...
    def echelon_form(self) -> Any: ...
    def left_kernel_matrix(self) -> Any: ...
    def right_kernel_matrix(self) -> Any: ...
    def stack(self, other: Any) -> Any: ...
    def augment(self, other: Any) -> Any: ...
    def matrix_from_columns(self, cols: Sequence[int]) -> Any: ...
    def submatrix(self, r: int, c: int, nr: int | None = None, nc: int | None = None) -> Any: ...
    def solve_right(self, b: Any) -> Any: ...
    def is_zero(self) -> bool: ...
    def base_ring(self) -> Any: ...


@runtime_checkable
class FFPolyProtocol(Protocol):
    """Univariate polynomial in ``GF(q)[x]``."""

    def is_zero(self) -> bool: ...
    def degree(self) -> int: ...
    def padded_list(self, n: int) -> list[Any]: ...
    def list(self) -> list[Any]: ...
    def shift(self, k: int) -> Any: ...
    def derivative(self) -> Any: ...
    def __call__(self, x: Any) -> Any: ...
    def eval_points(self, xs: Sequence[Any]) -> Any: ...
    def gcd(self, other: Any) -> Any: ...
    def xgcd(self, other: Any) -> tuple[Any, Any, Any]: ...
    def monic(self) -> Any: ...
    def leading_coefficient(self) -> Any: ...
    def parent(self) -> Any: ...


@runtime_checkable
class RSCodecProtocol(Protocol):
    """Plain ``[n, k, d = n - k + 1]`` Reed-Solomon codec on arbitrary eval points."""

    def parity_check_matrix(self) -> Any: ...
    def syndrome(self, r_arr: Any) -> Any: ...
    def decode_errors(self, r_arr: Any) -> Any: ...
    def decode_errors_erasures(self, r_arr: Any, era_mask: Sequence[int]) -> Any: ...
